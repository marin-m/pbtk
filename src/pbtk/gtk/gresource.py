#!/usr/bin/env python3
from os.path import dirname, realpath, exists, splitext, join
from os import stat, walk, scandir, access, W_OK
from subprocess import run
from shutil import which
from os import makedirs
from glob import iglob

from gi.repository import Gio

SCRIPT_DIR = dirname(realpath(__file__))
ASSETS_DIR = realpath(join(SCRIPT_DIR, 'assets'))
GENERATED_DIR = realpath(join(ASSETS_DIR, 'generated'))
RESOURCES_PATH = realpath(join(ASSETS_DIR, 'pbtk.gresource'))

makedirs(GENERATED_DIR, exist_ok=True)


# Create a templated window object, in order
# to parse the Cambalache-produced UI file

if not exists(RESOURCES_PATH) or (
    access(RESOURCES_PATH, W_OK)
    and which('blueprint-compiler')
    and which('glib-compile-resources')
    and max(
        meta.stat().st_mtime
        for dir_name, _, _ in walk(ASSETS_DIR)
        for meta in scandir(dir_name)
    )
    > stat(RESOURCES_PATH).st_mtime
):
    for blueprint_name in iglob('**.blp', recursive=True, root_dir=ASSETS_DIR):
        base_name, _ = splitext(blueprint_name)

        run(
            [
                'blueprint-compiler',
                'compile',
                '--output',
                join(GENERATED_DIR, base_name + '-autogenerated.ui'),
                base_name + '.blp',
            ],
            cwd=ASSETS_DIR,
        )
    run(['glib-compile-resources', RESOURCES_PATH + '.xml'], cwd=ASSETS_DIR)

GIO_RESOURCES = Gio.Resource.load(RESOURCES_PATH)
Gio.resources_register(GIO_RESOURCES)
