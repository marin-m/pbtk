#!/usr/bin/env python3

from pbtk.utils.common import extractors, load_proto_msgs, BASE_PATH
from pbtk.ui.templates.extractor_row import ExtractorRow
from pbtk.datamodel.extractor import Extractor
from pbtk.extractors import *

from importlib.metadata import version

import gi

gi.require_version('Gtk', '4.0')
gi.require_version('Adw', '1')

from gi.repository import Gtk, Adw, GObject, GLib, Gio

# (⚠️ TODO: Load from BLP file)


@Gtk.Template(
    resource_path='/re/fossplant/pbtk/templates/main_window-autogenerated.ui'
)
class MainWindow(Adw.ApplicationWindow):
    __gtype_name__ = 'MainWindow'

    app: Adw.Application

    about_dialog: Adw.AboutDialog
    debug_timer_source: int = None

    main_nav_view: Adw.NavigationView = Gtk.Template.Child()

    url_input_dialog: Adw.AlertDialog = Gtk.Template.Child()
    input_url_entry: Gtk.Entry = Gtk.Template.Child()
    input_url_buffer: Gtk.EntryBuffer = Gtk.Template.Child()

    open_dir_section: Adw.PreferencesGroup = Gtk.Template.Child()

    extractor_objs = GObject.Property(type=Gio.ListStore)  # Of Extractor
    extractors_list: Adw.PreferencesGroup = Gtk.Template.Child()

    extracting_status_page: Adw.StatusPage = Gtk.Template.Child()
    extraction_spinner: Adw.SpinnerPaintable = Gtk.Template.Child()
    extracting_progress_bar: Gtk.ProgressBar = Gtk.Template.Child()
    extraction_next_steps: Gtk.Box = Gtk.Template.Child()
    extraction_text_view: Gtk.TextView = Gtk.Template.Child()
    extraction_text_buffer: Gtk.TextBuffer = Gtk.Template.Child()

    endpoint_msg_section: Adw.PreferencesGroup = Gtk.Template.Child()
    endpoint_msg_names: Gtk.StringList = Gtk.Template.Child()

    transport_type_list: Adw.ComboRow = Gtk.Template.Child()

    global_extraction_dir = GObject.Property(type=str)

    def __init__(self, app):
        super().__init__()

        self.set_application(app)
        self.app = app

        # Pre-draw about dialog using AppStream metadata

        self.about_dialog = Adw.AboutDialog.new_from_appdata(
            '/re/fossplant/pbtk/re.fossplant.pbtk.metainfo.xml',
            version('pbtk'),
        )
        self.about_dialog.set_debug_info_filename('pbtk-debug-info.txt')
        self.about_dialog.set_developer_name('')
        self.about_dialog.set_developers(
            ['Marin Moulinier https://fossplant.re/']
        )

        def on_closed(*args):
            self.about_dialog.set_visible(False)

        self.about_dialog.connect('closed', on_closed)

        # Pre-draw URL prompt dialog

        self.url_input_dialog.add_response('cancel', 'Cancel')
        self.url_input_dialog.add_response('ok', 'Ok')

        self.url_input_dialog.set_response_appearance(
            'ok', Adw.ResponseAppearance.SUGGESTED
        )

        # Perform data bindings

        self.bind_data()

        # Connect actions

        self.connect_actions()

        # Connect signals

        self.connect_signals()

        # Reset the default UI state

        self.reset_state()

    def bind_data(self):
        self.global_extraction_dir = str(BASE_PATH / 'protos')

        self.open_dir_section.set_description(
            ('Location: %s') % self.global_extraction_dir
        )

        self.extractor_objs = Gio.ListStore.new(Extractor)

        for name, extractor_obj in extractors.items():
            self.extractor_objs.append(extractor_obj)

        self.extractors_list.bind_model(
            self.extractor_objs, ExtractorRow, self
        )

        # 🪧➡️ WIP ⚠️: BIND EXTRACTORS LIST TO UI PANEL #1
        # Cf. https://lazka.github.io/pgi-docs/Adw-1/classes/PreferencesGroup.html#Adw.PreferencesGroup.bind_model

    def connect_actions(self):

        def show_about(*args):

            self.about_dialog.set_visible(True)

            if not self.debug_timer_source:

                def update_debug_info():
                    self.about_dialog.set_debug_info(
                        '\n'.join(
                            self.app.logging_central.scrollback_handler.logs
                        )
                    )

                    if not self.about_dialog.is_visible():
                        self.debug_timer_source = None
                        return GLib.SOURCE_REMOVE
                    else:
                        return GLib.SOURCE_CONTINUE

                self.debug_timer_source = GLib.timeout_add_seconds(
                    1, update_debug_info
                )
                update_debug_info()

            self.about_dialog.present(self)

        self.add_simple_action('show-about', show_about)

        def pick_proto_file(*args):

            def load_bytes_cb(open_result, result):
                try:
                    data: bytes = open_result.load_bytes_finish(result)[
                        0
                    ].get_data()
                except GLib.GError as err:
                    dialog = Adw.AlertDialog.new(
                        'Could not read file', err.message
                    )
                    dialog.add_response('ok', 'Ok')
                    dialog.set_default_response('ok')
                    dialog.set_close_response('ok')
                    dialog.choose(self, None, None)
                else:
                    msg_names = [
                        item.name
                        for item in load_proto_msgs(open_result.get_path())
                    ]

                    self.endpoint_msg_names.splice(
                        0, self.endpoint_msg_names.get_n_items(), msg_names
                    )

                    self.endpoint_msg_section.set_description(
                        'Pick a message loaded from "<a href="file://%s">%s</a>":'
                        % (
                            GLib.markup_escape_text(open_result.get_path()),
                            GLib.markup_escape_text(open_result.get_path()),
                        )
                    )

                    # ⚠️ ⚠️ TODO:
                    # We should warn "There is no message defined in this .proto."
                    # to the user here instead of loading the view when adequate.

                    # (... also, develop the rest of the interactivity for the
                    #  "Step 2" panel, etc.)

                    self.main_nav_view.push_by_tag('endpoints_page')

            def file_picked(file_dialog: Gtk.FileDialog, task: Gio.Task):
                try:
                    open_result: Gio.File = file_dialog.open_finish(task)

                except GLib.GError as err:
                    if err.message != 'Dismissed by user':
                        dialog = Adw.AlertDialog.new(
                            'Could not open file', err.message
                        )
                        dialog.add_response('ok', 'Ok')
                        dialog.set_default_response('ok')
                        dialog.set_close_response('ok')
                        dialog.choose(self, None, None)
                else:
                    open_result.load_bytes_async(None, load_bytes_cb)

            proto_filter = Gtk.FileFilter.new()
            proto_filter.set_name('Protobuf definition (*.proto)')
            proto_filter.add_suffix('proto')

            filters = Gio.ListStore.new(Gtk.FileFilter)
            filters.append(proto_filter)

            file_picker = Gtk.FileDialog()
            file_picker.set_initial_folder(
                Gio.File.new_for_path(self.global_extraction_dir)
            )
            file_picker.set_filters(filters)
            file_picker.open(self, callback=file_picked)

        self.add_simple_action('pick-proto-file', pick_proto_file)

        def open_proto_dir(*args):
            proto_dir = Gio.File.new_for_path(self.global_extraction_dir)
            Gtk.FileLauncher.new(proto_dir).launch(self, None, None)

        self.add_simple_action('open-proto-dir', open_proto_dir)

        def go_back_to_main(*args):
            self.main_nav_view.pop_to_tag('main_page')

        self.add_simple_action('go-back-to-main', go_back_to_main)

    def add_simple_action(self, name, callback, param_type=None):

        action = Gio.SimpleAction.new(name, param_type)
        action.connect('activate', callback)
        self.add_action(action)

    def connect_signals(self):
        pass  # TODO

    def reset_state(self):
        pass  # TODO
