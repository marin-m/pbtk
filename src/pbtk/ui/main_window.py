#!/usr/bin/env python3

from pbtk.utils.common import (
    extractors,
    transports,
    load_proto_msgs,
    ProtoMessageDeclaration,
    insert_endpoint,
    BASE_PATH,
)
from pbtk.ui.templates.extractor_row import ExtractorRow
from pbtk.datamodel.transport import TransportDefinition
from pbtk.datamodel.extractor import Extractor
from pbtk.extractors import *

from importlib.metadata import version
from urllib.parse import urlparse

import gi

gi.require_version('Gtk', '4.0')
gi.require_version('Adw', '1')

from gi.repository import Gtk, Adw, GObject, GLib, Gio

# (⚠️ TODO: Load from BLP file)


@Gtk.Template(
    resource_path='/re/fossplant/pbtk/templates/main_window-autogenerated.ui'
)
class MainWindow(Adw.ApplicationWindow):
    __gtype_name__ = 'MainWindow'

    app: Adw.Application

    about_dialog: Adw.AboutDialog
    debug_timer_source: int = None

    main_nav_view: Adw.NavigationView = Gtk.Template.Child()

    url_input_dialog: Adw.AlertDialog = Gtk.Template.Child()
    input_url_entry: Gtk.Entry = Gtk.Template.Child()
    input_url_buffer: Gtk.EntryBuffer = Gtk.Template.Child()

    open_dir_section: Adw.PreferencesGroup = Gtk.Template.Child()

    extractor_objs = GObject.Property(type=Gio.ListStore)  # Of Extractor
    extractors_list: Adw.PreferencesGroup = Gtk.Template.Child()

    global_extraction_dir = GObject.Property(type=str)

    # Step 1 - Extract Proto cefinitions from file

    extracting_status_page: Adw.StatusPage = Gtk.Template.Child()
    extraction_spinner: Adw.SpinnerPaintable = Gtk.Template.Child()
    extracting_progress_bar: Gtk.ProgressBar = Gtk.Template.Child()
    extraction_next_steps: Gtk.Box = Gtk.Template.Child()
    extraction_text_view: Gtk.TextView = Gtk.Template.Child()
    extraction_text_buffer: Gtk.TextBuffer = Gtk.Template.Child()

    # Step #2 - Define an HTTPS endpoint

    selected_req_proto = GObject.Property(type=Gio.File)
    selected_resp_proto = GObject.Property(type=Gio.File)

    endpoint_url: Adw.EntryRow = Gtk.Template.Child()

    endpoint_msg_section: Adw.PreferencesGroup = Gtk.Template.Child()
    endpoint_msg_list: Adw.ComboRow = Gtk.Template.Child()
    endpoint_req_msgs: Gio.ListStore = Gtk.Template.Child()

    transport_type_list: Adw.ComboRow = Gtk.Template.Child()
    transport_type_objs: Gio.ListStore = Gtk.Template.Child()

    sample_data_section: Adw.PreferencesGroup = Gtk.Template.Child()
    pb_param_subform: Adw.EntryRow = Gtk.Template.Child()

    endpoint_parse_resp: Adw.SwitchRow = Gtk.Template.Child()
    endpoint_resp_msg_file: Adw.ActionRow = Gtk.Template.Child()
    endpoint_resp_msg_list: Adw.ComboRow = Gtk.Template.Child()
    endpoint_resp_msgs: Gio.ListStore = Gtk.Template.Child()

    sample_data_buffer: Gtk.TextBuffer = Gtk.Template.Child()

    def __init__(self, app):
        super().__init__()

        self.set_application(app)
        self.app = app

        # Pre-draw about dialog using AppStream metadata

        self.about_dialog = Adw.AboutDialog.new_from_appdata(
            '/re/fossplant/pbtk/re.fossplant.pbtk.metainfo.xml',
            version('pbtk'),
        )
        self.about_dialog.set_debug_info_filename('pbtk-debug-info.txt')
        self.about_dialog.set_developer_name('')
        self.about_dialog.set_developers(
            ['Marin Moulinier https://fossplant.re/']
        )

        def on_closed(*args):
            self.about_dialog.set_visible(False)

        self.about_dialog.connect('closed', on_closed)

        # Pre-draw URL prompt dialog

        self.url_input_dialog.add_response('cancel', 'Cancel')
        self.url_input_dialog.add_response('ok', 'Ok')

        self.url_input_dialog.set_response_appearance(
            'ok', Adw.ResponseAppearance.SUGGESTED
        )

        # Perform data bindings

        self.bind_data()

        # Connect actions

        self.connect_actions()

        # Connect signals

        self.connect_signals()

    def bind_data(self):
        self.global_extraction_dir = str(BASE_PATH / 'protos')

        self.open_dir_section.set_description(
            ('Location: %s') % self.global_extraction_dir
        )

        self.extractor_objs = Gio.ListStore.new(Extractor)

        for name, extractor_obj in extractors.items():
            self.extractor_objs.append(extractor_obj)

        self.extractors_list.bind_model(
            self.extractor_objs, ExtractorRow, self
        )

        for transport in transports.values():
            self.transport_type_objs.append(transport)

        self.update_endpoint_data_type()

        self.endpoint_parse_resp.bind_property(
            'active',
            self.endpoint_resp_msg_file,
            'visible',
            GObject.BindingFlags.SYNC_CREATE,
        )

        self.endpoint_parse_resp.bind_property(
            'active',
            self.endpoint_resp_msg_list,
            'visible',
            GObject.BindingFlags.SYNC_CREATE,
        )

    def connect_actions(self):

        def show_about(*args):

            self.about_dialog.set_visible(True)

            if not self.debug_timer_source:

                def update_debug_info():
                    self.about_dialog.set_debug_info(
                        '\n'.join(
                            self.app.logging_central.scrollback_handler.logs
                        )
                    )

                    if not self.about_dialog.is_visible():
                        self.debug_timer_source = None
                        return GLib.SOURCE_REMOVE
                    else:
                        return GLib.SOURCE_CONTINUE

                self.debug_timer_source = GLib.timeout_add_seconds(
                    1, update_debug_info
                )
                update_debug_info()

            self.about_dialog.present(self)

        self.add_simple_action('show-about', show_about)

        def pick_proto_file(*args):

            def load_bytes_cb(open_result: Gio.File, result: Gio.AsyncResult):
                try:
                    _data: bytes = open_result.load_bytes_finish(result)[
                        0
                    ].get_data()

                except GLib.GError as err:
                    self.alert_popup('Could not read file', err.message)

                else:
                    messages: list[ProtoMessageDeclaration] = list(
                        load_proto_msgs(open_result.get_path())
                    )

                    if not messages:
                        self.alert_popup(
                            'There is no message defined in this .proto.'
                        )
                        return

                    self.endpoint_req_msgs.splice(
                        0, self.endpoint_req_msgs.get_n_items(), messages
                    )

                    self.endpoint_resp_msgs.splice(
                        0,
                        self.endpoint_resp_msgs.get_n_items(),
                        messages,
                    )

                    self.endpoint_msg_section.set_description(
                        'Pick a message loaded from "<a href="file://%s">%s</a>":'
                        % (
                            GLib.markup_escape_text(open_result.get_path()),
                            GLib.markup_escape_text(open_result.get_path()),
                        )
                    )

                    self.endpoint_resp_msg_file.set_subtitle(
                        open_result.get_path()
                    )

                    self.selected_req_proto = open_result
                    self.selected_resp_proto = open_result

                    self.main_nav_view.push_by_tag('endpoints_page')

            def file_picked(
                file_dialog: Gtk.FileDialog, task: Gio.AsyncResult
            ):
                try:
                    open_result: Gio.File = file_dialog.open_finish(task)

                except GLib.GError as err:
                    if err.message != 'Dismissed by user':
                        self.alert_popup('Could not open file', err.message)
                else:
                    open_result.load_bytes_async(None, load_bytes_cb)

            proto_filter = Gtk.FileFilter.new()
            proto_filter.set_name('Protobuf definition (*.proto)')
            proto_filter.add_suffix('proto')

            filters = Gio.ListStore.new(Gtk.FileFilter)
            filters.append(proto_filter)

            file_picker = Gtk.FileDialog()
            file_picker.set_initial_folder(
                Gio.File.new_for_path(self.global_extraction_dir)
            )
            file_picker.set_filters(filters)
            file_picker.open(self, callback=file_picked)

        self.add_simple_action('pick-proto-file', pick_proto_file)

        def open_proto_dir(*args):
            proto_dir = Gio.File.new_for_path(self.global_extraction_dir)
            Gtk.FileLauncher.new(proto_dir).launch(self, None, None)

        self.add_simple_action('open-proto-dir', open_proto_dir)

        def go_back_to_main(*args):
            self.main_nav_view.pop_to_tag('main_page')

        self.add_simple_action('go-back-to-main', go_back_to_main)

        def pick_resp_msg(*args):

            def load_bytes_cb(open_result: Gio.File, result: Gio.AsyncResult):
                try:
                    _data: bytes = open_result.load_bytes_finish(result)[
                        0
                    ].get_data()
                except GLib.GError as err:
                    self.alert_popup('Could not read file', err.message)
                else:
                    msgs: list[ProtoMessageDeclaration] = list(
                        load_proto_msgs(open_result.get_path())
                    )

                    if not msgs:
                        self.alert_popup(
                            'There is no message defined in this .proto.'
                        )
                        return

                    self.endpoint_resp_msgs.splice(
                        0,
                        self.endpoint_resp_msgs.get_n_items(),
                        msgs,
                    )

                    self.endpoint_resp_msg_file.set_subtitle(
                        open_result.get_path()
                    )

                    self.selected_resp_proto = open_result

            def file_picked(
                file_dialog: Gtk.FileDialog, task: Gio.AsyncResult
            ):
                try:
                    open_result: Gio.File = file_dialog.open_finish(task)

                except GLib.GError as err:
                    if err.message != 'Dismissed by user':
                        self.alert_popup('Could not open file', err.message)
                else:
                    open_result.load_bytes_async(None, load_bytes_cb)

            proto_filter = Gtk.FileFilter.new()
            proto_filter.set_name('Protobuf definition (*.proto)')
            proto_filter.add_suffix('proto')

            filters = Gio.ListStore.new(Gtk.FileFilter)
            filters.append(proto_filter)

            file_picker = Gtk.FileDialog()
            file_picker.set_initial_folder(
                Gio.File.new_for_path(self.global_extraction_dir)
            )
            file_picker.set_filters(filters)
            file_picker.open(self, callback=file_picked)

        self.add_simple_action('pick-resp-msg', pick_resp_msg)

        def create_endpoint(*args):
            request_pb: ProtoMessageDeclaration = (
                self.endpoint_msg_list.get_selected_item()
            )
            url: str = self.endpoint_url.get_text()
            transport: TransportDefinition = (
                self.transport_type_list.get_selected_item()
            )
            sample_data = self.sample_data_buffer.props.text
            pb_param = self.pb_param_subform.get_text()
            has_resp_pb = self.endpoint_parse_resp.get_active()
            resp_pb = self.endpoint_resp_msg_list.get_selected_item()

            if not (
                request_pb
                and urlparse(url).netloc
                and transport
                and (not transport.transport_class.has_pb_param or pb_param)
                and (not has_resp_pb or resp_pb)
            ):
                self.alert_popup(
                    'Please fill all relevant information fields.'
                )
                return

            else:
                json = {
                    'request': {
                        'transport': transport.transport_class.name,
                        'proto_path': self.selected_req_proto.get_path()
                        .replace(str(BASE_PATH / 'protos'), '')
                        .strip('/\\'),
                        'proto_msg': request_pb.name,
                        'url': url,
                    }
                }
                if transport.transport_class.has_pb_param:
                    json['request']['pb_param'] = pb_param

                sample_data = list(filter(None, sample_data.split('\n')))
                if sample_data:
                    transport_obj = transport.transport_class
                    transport_obj = transport_obj(pb_param, url)

                    for sample_id, sample in enumerate(sample_data):
                        try:
                            sample = transport_obj.serialize_sample(sample)
                        except Exception:
                            self.alert_popup(
                                'Some of your sample data is not in the specified format.'
                            )
                            return

                        if not sample:
                            self.alert_popup(
                                "Some of your sample data didn't contain the Protobuf parameter key you specified."
                            )
                            return

                        sample_data[sample_id] = sample

                    json['request']['samples'] = sample_data

                if has_resp_pb:
                    json['response'] = {
                        'format': 'raw_pb',
                        'proto_path': self.selected_resp_proto.get_path()
                        .replace(str(BASE_PATH / 'protos'), '')
                        .strip('/\\'),
                        'proto_msg': resp_pb.name,
                    }
                insert_endpoint(BASE_PATH / 'endpoints', json)

                self.alert_popup('Endpoint created successfully.')

                self.main_nav_view.pop_to_tag('main_page')

        self.add_simple_action('create-endpoint', create_endpoint)

    def add_simple_action(self, name, callback, param_type=None):

        action = Gio.SimpleAction.new(name, param_type)
        action.connect('activate', callback)
        self.add_action(action)

    def alert_popup(self, *args):

        dialog = Adw.AlertDialog.new(*args)
        dialog.add_response('ok', 'Ok')
        dialog.set_default_response('ok')
        dialog.set_close_response('ok')
        dialog.choose(self, None, None)

    def connect_signals(self):
        self.transport_type_list.connect(
            'notify::selected-item', self.update_endpoint_data_type
        )

    def update_endpoint_data_type(self, *args):
        current_transport = (
            self.transport_type_list.get_selected_item().transport_class
        )

        self.sample_data_section.set_description(
            'Please type one sample of data per line (in the form of %s)'
            % current_transport.ui_data_form
        )

        self.pb_param_subform.set_visible(current_transport.has_pb_param)
